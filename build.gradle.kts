group = "io.github.gabepurc"
version = "0.1.0"

repositories {
	mavenCentral()
}

dependencies {
	testImplementation(platform("org.junit:junit-bom:5.11.4"))
	testImplementation("org.junit.jupiter:junit-jupiter")
	testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

// Java 17 bytecode: the plugin loads in any Gradle a Minecraft mod build runs (Loom and ModDevGradle need 17 or newer).
tasks.withType<JavaCompile>().configureEach {
	options.release = 17
	options.encoding = "UTF-8"
	options.compilerArgs.add("-Xlint:unchecked")
}

// The version, compiled in: the daemon and its clients compare it to tell an old daemon from a current one.
val projectVersion = project.version.toString()
val generateVersion = tasks.register("generateVersion") {
	val out = layout.buildDirectory.dir("generated/sources/version")
	inputs.property("version", projectVersion)
	outputs.dir(out)
	doLast {
		val file = out.get().file("io/github/gabepurc/spawnproof/Version.java").asFile
		file.parentFile.mkdirs()
		file.writeText(
			"package io.github.gabepurc.spawnproof;\n\n" +
				"/** Generated by build.gradle.kts. */\n" +
				"public final class Version {\n" +
				"\tpublic static final String VERSION = \"$projectVersion\";\n\n" +
				"\tprivate Version() {}\n" +
				"}\n"
		)
	}
}
sourceSets.main { java.srcDir(generateVersion) }

tasks.jar {
	manifest {
		attributes("Main-Class" to "io.github.gabepurc.spawnproof.cli.Main", "Implementation-Version" to projectVersion)
	}
}

tasks.test {
	useJUnitPlatform()
	testLogging {
		events("failed")
		exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
	}
}

